#!/bin/sh
#
# Build the CH32V0x in-SRAM flashstub and regenerate the Rust image the driver
# embeds:
#
#   ch32v0x_write.c --gcc(rv32ec)--> ch32v0x_write.o / .bin / .asm
#                                 \
#                                  +--> ../src/flashstub.rs  (embedded by the Rust driver)
#                                  +--> ch32v0x_write.stub   (C array, legacy)
#
# Run from anywhere: sh ch32v0x_mkstub.sh
#
export TOOLPATH=/riscv/xpack-14.2.0-2/bin/riscv-none-elf-

HERE=$(cd "$(dirname "$0")" && pwd)
SRC_DIR=${HERE}/../src
BYTES_PER_LINE=12
SCRIPT=$(basename "$0")

fail() {
  echo "*** FAIL ** $1"
  exit -1
}

# Emit ../src/flashstub.rs from the binary image just built.
gen_rust() {
  name=$1
  out=${SRC_DIR}/flashstub.rs
  echo "Generating $out"

  {
    echo "// @generated by flashstub/${SCRIPT} -- do not edit by hand."
    echo "//"
    echo "// ${name}.bin: in-SRAM flash program stub (rv32ec_zicsr / ilp32e)."
    echo "// Regenerate: cd blackmagic_addon/target/rs_ch32v00x/flashstub && sh ${SCRIPT}"
    echo
    echo "/// Flashstub binary for high-speed page programming."
    echo "pub const CH32V0X_WRITE_BIN: &[u8] = &["
    xxd -c ${BYTES_PER_LINE} -p ${name}.bin | awk '
      {
        printf "   "
        for (i = 1; i <= length($0); i += 2)
          printf " 0x%s,", substr($0, i, 2)
        printf "\n"
      }'
    echo "];"
    echo
    echo "/// Length in bytes of \`CH32V0X_WRITE_BIN\`."
    echo "pub const CH32V0X_WRITE_BIN_LEN: usize = $(wc -c < ${name}.bin);"
    echo
    echo "// The image and its declared length must stay in sync."
    echo "const _: () = assert!(CH32V0X_WRITE_BIN.len() == CH32V0X_WRITE_BIN_LEN);"
  } > ${out}.tmp && mv ${out}.tmp ${out} || fail rust
}

gen() {
  echo "Generating $1"
  name=$1

  ${TOOLPATH}gcc \
    -g \
    -march=rv32ec_zicsr -mabi=ilp32e \
    -O3 -ffreestanding -nostdlib -fomit-frame-pointer \
    -I../../../flashstub \
    $1.c -o $1.o \
    -c || fail gcc
  ${TOOLPATH}objcopy -Obinary $1.o $1.bin || fail objcopy
  ${TOOLPATH}objdump -Sd $1.o >$1.asm || fail objdump

  # C array form, kept for reference / non-Rust consumers.
  xxd -i $1.bin >$1.h1
  cat $1.h1 | sed 's/unsigned char/const unsigned char/g' | head -c -1 >$1.stub
  \rm -f $1.h1

  gen_rust $name
}

cd "${HERE}" || fail cd
gen ch32v0x_write

echo "Done."


pub const FMC_CTL_STRT: u32 = 1 << 6;     // Start erase/program (cleared by hardware)
pub const FMC_CTL_LOCK: u32 = 1 << 7;     // FPEC and CTLR locked
pub const FMC_CTL_FLOCK: u32 = 1 << 15;   // Fast programming/erase locked

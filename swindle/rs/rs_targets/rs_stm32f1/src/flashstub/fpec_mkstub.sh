#!/bin/sh
#
# Regenerate the two FPEC flash-programming stubs the Rust driver loads into the target.
#
#   ./fpec_mkstub.sh
#
# Builds `fpec_write.c` twice - once for the 16-bit program steps of the STM32F0/F1/F3
# parts, once for the 32-bit steps of the GD32/AT32 clones - and rewrites the matching
# `../../flashstub_write16.rs` / `../../flashstub_write32.rs` (crate `src/flashstub_write*.rs`),
# the byte images `rs_stm32f1::flashstub_write` copies into the target's SRAM. This is a
# manual, developer-only step: it needs an ARM C toolchain, while the probe build only
# compiles the generated Rust files. The generated files are therefore checked in, and
# this script is here to reproduce them.
#
# Override the toolchain with `ARM_GCC=/path/to/arm-none-eabi-gcc ./fpec_mkstub.sh`.
# (Only GCC can build these stubs: the function is `naked` and still contains C
# statements, which current clang rejects outright.)
set -eu

ARM_GCC=${ARM_GCC:-/arm/15.2.1/bin/arm-none-eabi-gcc}
PREFIX=$(dirname "${ARM_GCC}")/arm-none-eabi-
OBJCOPY=${OBJCOPY:-${PREFIX}objcopy}
OBJDUMP=${OBJDUMP:-${PREFIX}objdump}
# The stub has to run on the oldest cores of the family (Cortex-M3/M23), so keep the
# baseline CPU; the FPEC sits at a fixed address, so no headers are needed.
CPU=${CPU:--mcpu=cortex-m3}

SRC=fpec_write

build_stub() {
    width=$1
    rm -f "${SRC}${width}.o" "${SRC}${width}.bin" "${SRC}${width}.asm"
    "${ARM_GCC}" "${SRC}.c" -g -O2 -c ${CPU} -o "${SRC}${width}.o" -nostdlib -I ../../../include -DFPEC_WRITE_WIDTH="${width}"
    "${OBJCOPY}" -Obinary "${SRC}${width}.o" "${SRC}${width}.bin"
    "${OBJDUMP}" -S "${SRC}${width}.o" >"${SRC}${width}.asm"
}

# The bytes live in one checked-in Rust file per flavour so the driver has no hand-copied
# array. `name` is the constant prefix, `what` the flavour the doc comment spells out.
emit_rust() {
    width=$1
    out=$2
    name=$3
    what=$4
    bin="${SRC}${width}.bin"
    length=$(wc -c <"${bin}" | tr -d ' ')
    {
        printf '%s\n' \
            "//! Machine code of the FPEC flash-programming stub (${what})." \
            '//!' \
            '//! GENERATED by `src/flashstub/fpec_mkstub.sh` from `src/flashstub/fpec_write.c`:' \
            '//! run that script after touching the stub source and commit the result. The' \
            '//! probe build never runs it (an ARM C toolchain would be needed for that).' \
            '' \
            '/// Stub length in bytes.' \
            "pub const ${name}_WRITE_BIN_LEN: usize = ${length};" \
            '' \
            '/// The stub itself: `bkpt 1` once the chunk is programmed, `bkpt 0` when the flash' \
            '/// controller reported an error.' \
            "pub static ${name}_WRITE_BIN: [u8; ${name}_WRITE_BIN_LEN] = ["
        # `xxd -i` prints a C array: turn it into a Rust one line by line -- C
        # declaration and length variable dropped, closing brace translated, bytes
        # re-indented to rustfmt's four spaces with a trailing comma on every line.
        xxd -i -c 16 "${bin}" | awk '
            NR == 1 { next }
            /_len =/ { next }
            /^};$/ { print "];"; next }
            /^  / { line = substr($0, 3); print "    " line ((line ~ /,$/) ? "" : ",") }
        '
    } >"${out}"
}

build_stub 2
build_stub 4
emit_rust 2 ../flashstub_write16.rs STM32F1 "16-bit program steps"
emit_rust 4 ../flashstub_write32.rs GD32 "32-bit program steps"
rm -f "${SRC}2.o" "${SRC}2.bin" "${SRC}4.o" "${SRC}4.bin"
printf '%s\n' "wrote ../flashstub_write16.rs and ../flashstub_write32.rs - ${SRC}2.asm/${SRC}4.asm kept for inspection"

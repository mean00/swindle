#!/bin/sh
#
# Turn the RP2040 DMA-sniffer CRC32 image into the Rust module both RP drivers embed:
#
#   ./flashstub_crc32_mkstub.sh
#
#   rp2040_crc32.stub --> ../flashstub_crc32.rs (crate `src/flashstub_crc32.rs`)
#
# The `.stub` is the checked-in C array form of `rp2040_crc32.c`, built by
# `rp2040_crc32_mkstub.sh` next to this script; nothing here reads the blackmagic tree.
# RP2040 and RP2350 share the image: both park it at the base of SRAM and let it stream the
# range through the DMA sniffer.
#
# Like the STM32 stub generators this is a manual, developer-only step: the probe build
# only compiles the generated Rust file, which is checked in.
set -eu

HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
CRC_STUB="${HERE}/rp2040_crc32.stub"

python3 - "${CRC_STUB}" "${HERE}/../flashstub_crc32.rs" <<'PY'
import re
import sys

crc_src, crc_out = sys.argv[1:3]


def hex_values(text):
    """Every hexadecimal C integer literal of the file, in order."""
    return [int(value, 16) for value in re.findall(r"0x[0-9a-fA-F]+", text)]


# The stub file is already a byte image.
data = bytearray(hex_values(open(crc_src, encoding="ascii").read()))

lines = [
    "//! Machine code of the DMA sniffer CRC32 stub shared by the RP drivers.",
    "//!",
    "//! GENERATED by `src/flashstub/flashstub_crc32_mkstub.sh` from",
    "//! `src/flashstub/rp2040_crc32.stub`: run that script after touching the stub source",
    "//! and commit the result. The probe build never runs it (an ARM C toolchain and the",
    "//! `rp2040_crc32_mkstub.sh` step would be needed for that).",
    "",
    "/// Stub length in bytes.",
    f"pub const RP2040_CRC32_BIN_LEN: usize = {len(data)};",
    "",
    "/// The stub itself: `bkpt 1` with the checksum in r1.",
    "pub static RP2040_CRC32_BIN: [u8; RP2040_CRC32_BIN_LEN] = [",
]
for offset in range(0, len(data), 16):
    lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in data[offset : offset + 16]) + ",")
lines += ["];", ""]
with open(crc_out, "w", encoding="ascii") as out:
    out.write("\n".join(lines))
PY

printf '%s\n' "wrote ${HERE}/../flashstub_crc32.rs"

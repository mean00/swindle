#!/bin/sh
#
# Regenerate the SPI flash writer stub the RP2040 driver loads into SRAM:
#
#   ./rp2040_mkstub.sh
#
# Builds `rp2040_write.c` -- this crate's own copy of blackmagic's
# `src/target/flashstub/rp.c` -- for the Cortex-M0+ and rewrites
# `../flashstub_write.rs` (crate `src/flashstub_write.rs`), the byte image
# `rs_rp2040::flash` copies into the target's SRAM. The DMA sniffer CRC stub both RP
# drivers share lives in `rs_rp_common` (`src/flashstub/rp2040_crc32_mkstub.sh`).
#
# Like the STM32 stub generators this is a manual, developer-only step: it needs an ARM C
# toolchain, while the probe build only compiles the generated Rust file, which is checked
# in. Run it after touching the stub source and commit the result.
#
# Note: the checked-in `../flashstub_write.rs` was produced by blackmagic's release build
# of the same source. A local rebuild gives an equivalent image of a slightly different
# length (the compiler version differs), so only replace the checked-in image after
# validating it on hardware.
#
# Override the toolchain with `ARM_GCC=/path/to/arm-none-eabi-gcc ./rp2040_mkstub.sh`.
set -eu

ARM_GCC=${ARM_GCC:-/arm/15.2.1/bin/arm-none-eabi-gcc}
PREFIX=$(dirname "${ARM_GCC}")/arm-none-eabi-
OBJCOPY=${OBJCOPY:-${PREFIX}objcopy}
OBJDUMP=${OBJDUMP:-${PREFIX}objdump}
# The stub runs on the RP2040's Cortex-M0+, so keep the Thumb-1 baseline.
CPU=${CPU:--mcpu=cortex-m0plus}

HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
SRC=rp2040_write
cd "${HERE}"

rm -f "${SRC}.o" "${SRC}.elf" "${SRC}.bin" "${SRC}.asm"
"${ARM_GCC}" -mthumb ${CPU} -g -Os -ffreestanding -nostdlib -nostartfiles \
    -T "${SRC}.ld" "${SRC}.c" -o "${SRC}.elf"
"${OBJCOPY}" -Obinary -j.text "${SRC}.elf" "${SRC}.bin"
"${OBJDUMP}" -S "${SRC}.elf" >"${SRC}.asm"

length=$(wc -c <"${SRC}.bin" | tr -d ' ')
{
    printf '%s\n' \
        '//! Machine code of the RP2040 SPI flash writer stub.' \
        '//!' \
        '//! GENERATED by `src/flashstub/rp2040_mkstub.sh` from `src/flashstub/rp2040_write.c`:' \
        '//! run that script after touching the stub source and commit the result. The' \
        '//! probe build never runs it (an ARM C toolchain would be needed for that).' \
        '' \
        '/// Stub length in bytes.' \
        "pub const RP2040_WRITE_BIN_LEN: usize = ${length};" \
        '' \
        '/// The stub itself: `bkpt 1` once the chunk is programmed, the common stub exit code.' \
        'pub static RP2040_WRITE_BIN: [u8; RP2040_WRITE_BIN_LEN] = ['
    xxd -i -c 16 "${SRC}.bin" | awk '
        NR == 1 { next }
        /_len =/ { next }
        /^};$/ { print "];"; next }
        /^  / { line = substr($0, 3); print "    " line ((line ~ /,$/) ? "" : ",") }
    '
} >../flashstub_write.rs.tmp && mv ../flashstub_write.rs.tmp ../flashstub_write.rs

rm -f "${SRC}.o" "${SRC}.elf" "${SRC}.bin"
printf '%s\n' "wrote ../flashstub_write.rs - ${SRC}.asm kept for inspection"
